package io.netty.handler.codec.http2;

import io.netty.microbench.util.AbstractMicrobenchmark;
import org.openjdk.jmh.annotations.Benchmark;
import org.openjdk.jmh.annotations.BenchmarkMode;
import org.openjdk.jmh.annotations.Fork;
import org.openjdk.jmh.annotations.Measurement;
import org.openjdk.jmh.annotations.Mode;
import org.openjdk.jmh.annotations.OutputTimeUnit;
import org.openjdk.jmh.annotations.Param;
import org.openjdk.jmh.annotations.Scope;
import org.openjdk.jmh.annotations.Setup;
import org.openjdk.jmh.annotations.State;
import org.openjdk.jmh.annotations.Threads;
import org.openjdk.jmh.annotations.Warmup;

import java.util.concurrent.TimeUnit;

/** Construction and table configuration only; returned contexts escape to JMH's blackhole. */
@State(Scope.Thread)
@Threads(1)
@Fork(3)
@Warmup(iterations = 5, time = 1)
@Measurement(iterations = 5, time = 1)
@BenchmarkMode(Mode.AverageTime)
@OutputTimeUnit(TimeUnit.NANOSECONDS)
public class HpackInitializationBenchmark extends AbstractMicrobenchmark {
    @Param({ "0", "256", "4096" })
    public int tableSize;

    @Setup
    public void setup() throws Http2Exception {
        HpackStateBenchmark.newEncoder(tableSize);
    }

    @Benchmark
    public Object encoder() throws Http2Exception {
        return HpackStateBenchmark.newEncoder(tableSize);
    }

    @Benchmark
    public Object decoder() throws Http2Exception {
        HpackDecoder decoder = new HpackDecoder(Integer.MAX_VALUE);
        decoder.setMaxHeaderTableSize(tableSize);
        return decoder;
    }
}
